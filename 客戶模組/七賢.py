# -*- coding: utf-8 -*-
"""
客戶模組：七賢
==============
七賢的薪資檔：一個 Excel，月薪表叫「115年1月」～「115年12月」，
  薪資總額＝扣憑＋自提、退休自提＝自提、扣繳稅額＝國稅局＋扣繳；
  前期薪資讀去年 12 月；獎金一種一張表（員工年終、醫生年終、端午節、春節加成獎金…）。
這些固定的東西寫在下面的「預設設定」，畫面上只留會變的：獎金對應（含另放月份）、前期薪資。
"""
import 清冊共用 as 共

通用 = 共.取模組("通用")          # 借用通用模組做好的卡片（其他表卡）

名稱 = "七賢"
說明 = "月薪表 115年1月…、扣憑＋自提；獎金可另放月份"
預設客戶 = ["七賢"]
固定欄 = ("上期年終", "端午獎金", "中秋獎金", "本期年終")   # 這些固定在上面的欄位，不能另放月份
預設設定 = {
    "年度": 115,
    "月薪表": "{年度}年{月}月",
    "薪資總額": "扣憑＋自提", "退休自提": "自提", "扣繳稅額": "國稅局＋扣繳",
    "前期薪資表": "{前一年}年12月",          # 空白＝不讀前期薪資
    "獎金表": [["{前一年}員工年終", "上期年終"], ["{前一年}醫生年終", "上期年終"], ["{年度}端午節", "端午獎金"],
             ["春節加成獎金", "春節獎金"], ["旺年會表演獎", "旺年會表演獎"], ["旺年會各獎項", "旺年會各獎項"],
             ["十及五週年", "十及五週年"], ["發財獎", "發財獎"]],
    "獎金扣繳詞": "扣繳、國稅局、所得稅、代扣稅",
    "執行業務另開": True,
}


# 整理設定：產生清冊前，把七賢自己的設定換成共用核心看得懂的「其他表」
#   其他表的每一格：[工作表名稱, 填入清冊哪一欄, 月薪／獎金, 另放月份（可省略）]
def 整理設定(設):
    其他 = []
    if 共.清字(設.get("前期薪資表")):
        其他.append([設["前期薪資表"], "前期薪資", "月薪"])
    for x in 設.get("獎金表", []):
        月 = x[3] if len(x) > 3 else (x[2] if len(x) > 2 and isinstance(x[2], int) else "")
        其他.append([x[0], x[1], "獎金"] + ([月] if 月 and 共.清字(x[1]) not in 固定欄 else []))
    設["其他表"] = 其他
    return 設


def 頁面(介, 設):
    tk = 介.tk
    頁 = 介.加頁("獎金", "獎金對應")
    獎 = {}
    介.區塊標題(頁, "獎金對應",
             右邊=lambda 框: 介.文字按鈕(框, "＋ 新增", lambda: 獎["加"](), 色=介.PRIMARY_DARK, 移上色=介.TEXT,
                                     bg=介.BG).pack(side="right"))
    獎.update(通用.其他表卡(介, 頁, 設, 鍵="獎金表", 有格式=False, 固定欄=固定欄, 說明文字=(
        "一列一張獎金表，選要填進清冊哪一欄；金額欄、扣繳欄會自動找。表名開頭的年份會跟著清冊年度換。\n"
        "另放月份：每人在薪資總額下面多一列，金額放在選的月份（扣繳也加到那個月的扣繳稅額）；"
        "上期年終、端午、中秋、本期年終固定在上面欄位，不能另放。")))

    # 前期薪資（放在「檔案與年度」頁下面）
    介.區塊標題(介.檔案頁, "前期薪資")
    卡 = 介.卡片(介.檔案頁)
    卡.columnconfigure(1, weight=1)
    要讀 = tk.BooleanVar(value=bool(共.清字(設.get("前期薪資表"))))
    表變 = tk.StringVar()
    介.ttk.Checkbutton(卡, text="讀前期薪資", variable=要讀, style="奶茶.TCheckbutton",
                      command=lambda: 前期檢查()).grid(row=0, column=0, sticky="w", padx=(0, 14))
    前期選 = 介.下拉(卡, 介.資料["工作表"])
    前期選.configure(textvariable=表變)
    前期選.grid(row=0, column=1, sticky="ew")
    前期提示 = 介.小字(卡)
    前期提示.grid(row=1, column=1, sticky="w")
    模式 = {"v": 設.get("前期薪資表") or "{前一年}年12月"}

    def 前期檢查(e=None):
        年 = 介.目前年()
        if 年 and 表變.get().strip():
            模式["v"] = 共.轉模式(表變.get(), 年)
        前期選.configure(state="normal" if 要讀.get() else "disabled")
        if not 要讀.get():
            前期提示.configure(text="不讀前期薪資", fg=介.TEXT_GRAY)
        elif 介.資料["wb"] is None:
            前期提示.configure(text="", fg=介.TEXT_GRAY)
        elif 共.找工作表(介.資料["wb"], 表變.get()) is None:
            前期提示.configure(text="✗ 薪資檔找不到這張表", fg=介.ERR)
        else:
            前期提示.configure(text="✓ 填進清冊的「前期薪資」欄", fg=介.OK)
    for 事件 in ("<<ComboboxSelected>>", "<FocusOut>"):
        前期選.bind(事件, 前期檢查)

    # 進階：獎金扣繳詞、執行業務
    介.區塊標題(頁, "進階")
    卡2 = 介.卡片(頁)
    卡2.columnconfigure(1, weight=1)
    獎稅 = tk.StringVar(value=設.get("獎金扣繳詞", ""))
    執 = tk.BooleanVar(value=bool(設.get("執行業務另開")))
    介.標籤(卡2, "扣繳欄的認法").grid(row=0, column=0, sticky="w", padx=(0, 14), pady=4)
    框, _ = 介.輸入框(卡2, 獎稅)
    框.grid(row=0, column=1, sticky="ew", pady=4)
    介.小字(卡2, "獎金表標題含這些字的欄算扣繳稅額（用、分隔）").grid(row=1, column=1, sticky="w")
    介.ttk.Checkbutton(卡2, text="執行業務另外放一張「執行業務」工作表（只領執行業務的人，獎金也放那裡）",
                      variable=執, style="奶茶.TCheckbutton").grid(row=2, column=0, columnspan=2, sticky="w", pady=(6, 0))

    def 收集(設):
        獎["收集"](設)
        設["前期薪資表"] = 模式["v"] if 要讀.get() else ""
        設.update(獎金扣繳詞=獎稅.get().strip(), 執行業務另開=bool(執.get()))

    def 載入():
        獎["載入"]()
        前期選.configure(values=介.資料["工作表"])
        前期檢查()

    def 年改了():
        獎["年改了"]()
        年 = 介.目前年()
        if 年:
            表變.set(共.表名(模式["v"], 年))
        前期檢查()

    def 狀態():
        return {"獎金": 獎["狀態"]()}
    年改了()
    return {"收集": 收集, "載入": 載入, "年改了": 年改了, "樣板": 獎["樣板"], "狀態": 狀態}
