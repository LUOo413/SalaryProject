# -*- coding: utf-8 -*-
"""
客戶模組範本：自己讀薪資檔
==========================
（檔名開頭是 _ 的不會被載入。要用的時候：複製一份，改成客戶的名字，例如「A客戶.py」）

什麼時候用這個：薪資檔的格式用「通用」設定不出來，例如
  ・每個月一個 Excel（不是一個 Excel 裡每月一張表）
  ・一張表裡放全年，月份是橫的或直的
  ・薪資總額要好幾欄加總、要扣掉某些欄
  ・有好幾個專案／分店，要合在一起
做法：在「讀取」裡自己把每個人的金額讀出來，放進「資料來源」；
  之後的歸戶、填清冊、驗算、匯入檢查、人員名冊核對，共用核心都會做。
"""
import os
import 清冊共用 as 共

名稱 = "範本（自己讀）"
說明 = "每月一個 Excel 的例子"
預設設定 = {
    "資料夾": "",                 # 這個客戶自己的設定，畫面上可以改（見下面的「頁面」）
    "執行業務另開": False,
}
預設客戶 = []


# 讀取：回傳 (表們, 缺表, 警告)
#   設：這個客戶的設定；年：清冊年度；wb／wbf：畫面上選的薪資檔（只有值／有公式）
#   清冊欄：樣板上有哪些欄（例如 一月…十二月、前期薪資、上期年終…）
def 讀取(設, 年, wb, wbf, 清冊欄):
    表們, 缺表, 警告 = [], [], []
    資料夾 = 設.get("資料夾") or os.path.dirname(設["薪資檔"])
    for 月 in range(1, 13):
        路徑 = os.path.join(資料夾, f"{年}{月:02d}薪資.xlsx")          # ← 改成客戶的檔名規則
        if not os.path.exists(路徑):
            continue
        ws = 共.開活頁簿(路徑).worksheets[0]
        來源 = 共.資料來源(f"{年}年{月}月", 共.中文月[月 - 1], "月薪")   # 名稱、填進清冊哪一欄、月薪／獎金
        # 找標題列：第一欄寫「姓名」的那一列                          ← 改成客戶的格式
        標題列 = next(r for r in range(1, 15) if 共.清字(ws.cell(r, 2).value) == "姓名")
        標題 = {共.清字(ws.cell(標題列, c).value): c for c in range(1, ws.max_column + 1)}
        for r in range(標題列 + 1, ws.max_row + 1):
            名 = 共.清字(ws.cell(r, 標題["姓名"]).value)
            if not 共.是人名(名):
                continue
            值 = lambda 欄: 共.數字(ws.cell(r, 標題[欄]).value) if 欄 in 標題 else 0
            來源.加(名,
                  總額=值("本薪") + 值("加班費") + 值("伙食津貼"),   # 好幾欄加總
                  自提=值("勞退自提"),
                  稅=值("代扣所得稅"),
                  證=ws.cell(r, 標題["身分證"]).value if "身分證" in 標題 else "")
        來源.對合計("總額", sum(x["金"]["總額"] for x in 來源.列們))  # 有表上合計的話放表上合計，會寫進匯入檢查
        表們.append(來源)
    if not 表們:
        警告.append(f"{資料夾} 裡找不到 {年}01薪資.xlsx 這樣的檔案")
    return 表們, 缺表, 警告


# 頁面（可省略）：左邊選單多一頁，讓使用者改這個客戶自己的設定
def 頁面(介, 設):
    頁 = 介.加頁("範本", "每月檔案")
    介.區塊標題(頁, "每月的薪資檔放在哪個資料夾")
    卡 = 介.卡片(頁)
    卡.columnconfigure(1, weight=1)
    變 = 介.tk.StringVar(value=設.get("資料夾", ""))
    介.標籤(卡, "資料夾").grid(row=0, column=0, sticky="w", padx=(0, 14))
    框, _ = 介.輸入框(卡, 變)
    框.grid(row=0, column=1, sticky="ew")
    介.小字(卡, "空白＝跟「薪資檔」同一個資料夾；檔名要像 11501薪資.xlsx").grid(row=1, column=1, sticky="w")

    def 收集(設):
        設["資料夾"] = 變.get().strip()
    return {"收集": 收集}
