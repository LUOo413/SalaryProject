def 頁面(介, 設):
    科頁 = 介.加頁("科目", "科目分類")
    介.區塊標題(科頁, "科目分類")
    職 = 通用.職稱卡(介, 科頁, 設)

    年頁 = 介.加頁("前期", "前期年終")
    其 = {}
    介.區塊標題(年頁, "前期年終",
             右邊=lambda 框: 介.文字按鈕(框, "＋ 新增", lambda: 其["加"](), 色=介.PRIMARY_DARK, 移上色=介.TEXT,
                                     bg=介.BG).pack(side="right"))
    其.update(通用.其他表卡(介, 年頁, 設, 有格式=False, 有月份=False, 預設欄="前期年終", 說明文字=(
        "去年的年終、業績獎金表，金額欄自動找；好幾張表填同一欄（前期年終）會加在一起。表名開頭的年份會跟著清冊年度換。")))

    def 狀態():
        return {"科目": 職["狀態"](), "前期": 其["狀態"]()}
    return 通用.合併(職, 其, 狀態=狀態)
